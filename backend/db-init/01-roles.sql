  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO crew_app;
ALTER DEFAULT PRIVILEGES FOR ROLE crew_migrator IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO crew_app;
