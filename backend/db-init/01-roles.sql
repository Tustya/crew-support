CREATE ROLE crew_migrator NOSUPERUSER NOCREATEDB NOCREATEROLE LOGIN PASSWORD 'crew_migrator';
CREATE ROLE crew_app NOSUPERUSER NOCREATEDB NOCREATEROLE LOGIN PASSWORD 'crew_app';

ALTER SCHEMA public OWNER TO crew_migrator;

GRANT CONNECT ON DATABASE crew_support TO crew_migrator, crew_app;
GRANT USAGE ON SCHEMA public TO crew_app;

